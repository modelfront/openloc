// The translator reads a deck the way the audience does: slides in show
// order, shapes in tree order, a shape's alt text right after its text, then
// the slide's notes. Slide 1 is stored as slide2.xml and vice versa, so a
// parser that follows part names gets the order wrong.
func TestPPTXParse_ReadingOrderAndContexts(t *testing.T) {
	deck := pt.Deck{Slides: []pt.Slide{
		{Shapes: pt.TextBox(2, pt.P(pt.R("", "First slide"))), Notes: pt.P(pt.R("", "First notes"))},
		{
			Hidden: true,
			Shapes: pt.WithAlt(pt.TextBox(2, pt.P(pt.R("", "Boxed"))), "Box alt") +
				pt.WithAlt(pt.Group(3,
					pt.TextBox(4, pt.P(pt.R("", "In group"))),
					pt.Group(5, pt.TextBox(6, pt.P(pt.R("", "Nested")))),
				), "Group alt") +
				pt.Table(7, []string{pt.P(pt.R("", "A1")), pt.P(pt.R("", "B1"))}, []string{pt.P(pt.R("", "A2")), pt.P(pt.R("", "B2"))}),
		},
	}}
	content := swapSlideParts(t, pt.Build(deck))
	if !strings.Contains(pptxPart(t, content, "ppt/slides/slide2.xml"), "First slide") {
		t.Fatal("the first slide in show order must live in slide2.xml")
	}

	segs, err := PPTX{}.Parse(content)
	if err != nil {
		t.Fatal(err)
	}
	type row struct{ text, context string }
	var got []row
	for i, s := range segs {
		if s.Position != i {
			t.Errorf("segment %q has position %d, want %d", s.Text, s.Position, i)
		}
		got = append(got, row{s.Text, s.Context})
	}
	want := []row{
		{"First slide", "slide:1"},
		{"First notes", "slide:1/notes"},
		{"Boxed", "slide:2"},
		{"Box alt", "slide:2/alt"},
		{"In group", "slide:2"},
		{"Nested", "slide:2"},
		{"Group alt", "slide:2/alt"},
		{"A1", "slide:2/table"},
		{"B1", "slide:2/table"},
		{"A2", "slide:2/table"},
		{"B2", "slide:2/table"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("segments:\n got %v\nwant %v", got, want)
	}
}

// swapSlideParts makes the first slide in show order live in slide2.xml and
// the second in slide1.xml, by swapping the presentation's relationship
// targets and renaming the parts.
func swapSlideParts(t *testing.T, content []byte) []byte {
	t.Helper()
	rename := map[string]string{
		"ppt/slides/slide1.xml":            "ppt/slides/slide2.xml",
		"ppt/slides/slide2.xml":            "ppt/slides/slide1.xml",
		"ppt/slides/_rels/slide1.xml.rels": "ppt/slides/_rels/slide2.xml.rels",
		"ppt/slides/_rels/slide2.xml.rels": "ppt/slides/_rels/slide1.xml.rels",
	}
	return ooxmltest.RewriteZip(t, content, func(w *zip.Writer, f *zip.File) bool {
		body := ooxmltest.ReadZipEntry(t, f)
		name := f.Name
		switch {
		case f.Name == "ppt/_rels/presentation.xml.rels":
			body = strings.NewReplacer(`slides/slide1.xml`, `slides/slide2.xml`, `slides/slide2.xml`, `slides/slide1.xml`).Replace(body)
		case f.Name == "ppt/notesSlides/_rels/notesSlide1.xml.rels":
			body = strings.ReplaceAll(body, "../slides/slide1.xml", "../slides/slide2.xml")
		case rename[f.Name] != "":
			name = rename[f.Name]
		default:
			return false
		}
		ooxmltest.WriteZipEntry(t, w, name, body)
		return true
	})
}

// Notes pages carry a header, slide number and slide image besides the body;
// only the body is the speaker's text.
func TestPPTXParse_NotesBodyOnly(t *testing.T) {
	segs := pptxSegments(t, pt.Deck{Slides: []pt.Slide{{
		Shapes: pt.TextBox(2, pt.P(pt.R("", "Slide"))),
		Notes:  pt.P(pt.R("", "Say hello.")),
	}}})
	if got, want := pptxTexts(segs), []string{"Slide", "Say hello."}; !reflect.DeepEqual(got, want) {
		t.Errorf("texts = %q, want %q (the notes header and page number are not notes text)", got, want)
	}
}

// A field's text (the slide number, a date) is generated by PowerPoint, so it
// is a placeholder chip, not words to translate; a line break is a chip that
// reads as a newline.
func TestPPTXParse_FieldsAndLineBreaks(t *testing.T) {
	segs := pptxSegments(t, slide(pt.TextBox(2,
		pt.P(pt.R("", "Slide "), pt.SlideNumber(7), pt.R("", " of ten")),
		pt.P(pt.R("", "Quarterly"), pt.Br(), pt.R("", "results")),
	)))
	if len(segs) != 2 {
		t.Fatalf("got %d segments, want 2: %q", len(segs), pptxTexts(segs))
	}
	if segs[0].Text != "Slide  of ten" || segs[0].RichText != `Slide <x id="1" ctype="x-xml-fld"/> of ten` {
		t.Errorf("field: text %q rich %q", segs[0].Text, segs[0].RichText)
	}
	if segs[1].Text != "Quarterly\nresults" || segs[1].RichText != `Quarterly<x id="1" ctype="lb"/>results` {
		t.Errorf("line break: text %q rich %q", segs[1].Text, segs[1].RichText)
	}
}

// Alternate content lists the same shape for new and old readers; the first
// choice is what PowerPoint shows, and translating both would double the
// text.
func TestPPTXParse_AlternateContentFirstChoiceOnly(t *testing.T) {
	segs := pptxSegments(t, slide(
		`<mc:AlternateContent xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006">`+
			`<mc:Choice Requires="p14">`+pt.TextBox(2, pt.P(pt.R("", "New readers")))+`</mc:Choice>`+
			`<mc:Fallback>`+pt.TextBox(2, pt.P(pt.R("", "Old readers")))+`</mc:Fallback>`+
			`</mc:AlternateContent>`,
	))
	if got, want := pptxTexts(segs), []string{"New readers"}; !reflect.DeepEqual(got, want) {
		t.Errorf("texts = %q, want %q", got, want)
	}
}

// Keys come from positions, so two shapes with the same id (common after
// copy and paste) still get distinct keys, and parsing twice gives the same
// keys.
func TestPPTXParse_KeysUniqueAndStable(t *testing.T) {
	content := pt.Build(slide(
		pt.TextBox(5, pt.P(pt.R("", "One")), pt.P(pt.R("", "Two. Three."))),
		pt.TextBox(5, pt.P(pt.R("", "One"))),
	))
	first, err := PPTX{}.Parse(content)
	if err != nil {
		t.Fatal(err)
	}
	second, err := PPTX{}.Parse(content)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(first, second) {
		t.Error("parsing the same deck twice gave different segments")
	}
	seen := map[string]bool{}
	for _, s := range first {
		if seen[s.Key] {
			t.Errorf("duplicate key %s", s.Key)
		}
		seen[s.Key] = true
	}
	if len(first) != 4 {
		t.Errorf("got %d segments, want 4: %q", len(first), pptxTexts(first))
	}
}

// Empty placeholders, image-only slides and charts leave nothing to
// translate, and the upload says so rather than creating an empty job.
func TestPPTXParse_NoTextIsEmpty(t *testing.T) {
	deck := pt.Deck{Slides: []pt.Slide{{
		Shapes: pt.Placeholder(2, "title", pt.P(`<a:endParaRPr lang="en-US"/>`)) + pt.Picture(3, ""),
		Image:  pt.PNG,
	}}}
	_, err := PPTX{}.Parse(pt.Build(deck))
	if !errors.Is(err, common.ErrPPTXEmpty) {
		t.Fatalf("err = %v, want ErrPPTXEmpty", err)
	}
	if msg, ok := common.ImportMessage(err); !ok || !strings.Contains(msg, "no text to translate") {
		t.Errorf("ImportMessage = %q, %v", msg, ok)
	}
}

// A slide's title comes first whatever its place in the shape tree, so the
// translator reads the heading before the body; the rest keep tree order.
func TestPPTXParse_TitleFirst(t *testing.T) {
	segs := pptxSegments(t, pt.Deck{Slides: []pt.Slide{
		{Shapes: pt.TextBox(2, pt.P(pt.R("", "Body text"))) + pt.Placeholder(3, "title", pt.P(pt.R("", "Slide title"))) +
			pt.TextBox(4, pt.P(pt.R("", "More body")))},
		{Shapes: pt.TextBox(2, pt.P(pt.R("", "Tagline"))) + pt.WithAlt(pt.Placeholder(3, "ctrTitle", pt.P(pt.R("", "Cover title"))), "Logo")},
	}})
	want := []string{"Slide title", "Body text", "More body", "Cover title", "Logo", "Tagline"}
	if got := pptxTexts(segs); !reflect.DeepEqual(got, want) {
		t.Errorf("texts = %q, want %q", got, want)
	}
}
