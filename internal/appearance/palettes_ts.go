package appearance

import (
	"fmt"
	"sort"
	"strings"
)

// RenderTypeScript returns the contents of
// web/src/lib/builtin-palettes.generated.ts.
//
// Lives in the package rather than inside the generator so a test can compare
// its output against the checked-in file — editing palettes.go and forgetting
// `make types` would otherwise let the frontend silently drift from the Go
// source of truth, which is the exact failure this whole arrangement exists to
// prevent.
func RenderTypeScript() string {
	var b strings.Builder

	b.WriteString("// Code generated by internal/appearance/gen_ts_palettes.go. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Source of truth: internal/appearance/palettes.go. Regenerate with `make types`.\n")
	b.WriteString("// Bundled rather than fetched because palettes resolve before first paint.\n")
	b.WriteString("\nimport type { Palette, PaletteAnchors } from './palettes'\n\n")

	// Anchor role order + labels, so the editor and the Go validator agree on
	// both the set and how each role is described.
	b.WriteString("/** The 7 editable roles, in display order. */\n")
	b.WriteString("export const ANCHOR_KEYS = [\n")
	for _, k := range AnchorKeys {
		b.WriteString(fmt.Sprintf("  '%s',\n", k))
	}
	b.WriteString("] as const satisfies readonly (keyof PaletteAnchors)[]\n\n")

	b.WriteString("/** Human description of what each role paints. */\n")
	b.WriteString("export const ANCHOR_LABELS: Record<string, string> = {\n")
	labelKeys := make([]string, 0, len(AnchorLabels))
	for k := range AnchorLabels {
		labelKeys = append(labelKeys, k)
	}
	sort.Strings(labelKeys) // deterministic output — map order is random in Go
	for _, k := range labelKeys {
		b.WriteString(fmt.Sprintf("  %s: %q,\n", k, AnchorLabels[k]))
	}
	b.WriteString("}\n\n")

	b.WriteString(fmt.Sprintf("export const DEFAULT_LIGHT_ID = '%s'\n", DefaultLightPalette))
	b.WriteString(fmt.Sprintf("export const DEFAULT_DARK_ID = '%s'\n\n", DefaultDarkPalette))
	b.WriteString(fmt.Sprintf("export const MAX_CUSTOM_PALETTES = %d\n", MaxCustomPalettes))
	b.WriteString(fmt.Sprintf("export const MAX_PALETTE_NAME_LEN = %d\n\n", MaxNameLen))

	b.WriteString("export const BUILTIN_PALETTES: Palette[] = [\n")
	for _, p := range BuiltinPalettes {
		b.WriteString("  {\n")
		b.WriteString(fmt.Sprintf("    id: '%s',\n", p.ID))
		b.WriteString(fmt.Sprintf("    name: %q,\n", p.Name))
		b.WriteString(fmt.Sprintf("    mode: '%s',\n", p.Mode))
		b.WriteString("    builtin: true,\n")
		b.WriteString("    anchors: {\n")
		// AnchorKeys order, not map order, so regenerating produces an
		// identical file rather than a spurious diff.
		for _, k := range AnchorKeys {
			b.WriteString(fmt.Sprintf("      %s: '%s',\n", k, p.Anchors[k]))
		}
		b.WriteString("    },\n")
		b.WriteString("  },\n")
	}
	b.WriteString("]\n")

	return b.String()
}
