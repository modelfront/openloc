//go:build ignore

// gen_mock_querier.go reads the db.Querier interface and generates a mock
// implementation where every method panics with "not used". Methods that
// the pipeline tests actually implement are preserved in mock_querier_test.go
// manually — this generator only produces the stub file.
//
// Usage: go run gen_mock_querier.go
// Output: writes mock_querier_stubs_test.go in the current directory

package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"regexp"
	"strings"
)

func main() {
	// Find the querier.go file relative to this script or via env
	querierPath := os.Getenv("QUERIER_PATH")
	if querierPath == "" {
		// When run via go generate from internal/pipeline/, go up to find it
		candidates := []string{
			"../database/sqlcgen/querier.go",
			"internal/database/sqlcgen/querier.go",
		}
		for _, c := range candidates {
			if _, err := os.Stat(c); err == nil {
				querierPath = c
				break
			}
		}
		if querierPath == "" {
			log.Fatal("Cannot find querier.go. Run from project root or set QUERIER_PATH.")
		}
	}

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, querierPath, nil, 0)
	if err != nil {
		log.Fatalf("parse %s: %v", querierPath, err)
	}

	var methods []method
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "Querier" {
			return true
		}
		iface, ok := ts.Type.(*ast.InterfaceType)
		if !ok {
			return true
		}
		for _, m := range iface.Methods.List {
			if len(m.Names) == 0 {
				continue
			}
			ft, ok := m.Type.(*ast.FuncType)
			if !ok {
				continue
			}
			methods = append(methods, parseMethod(m.Names[0].Name, ft, fset))
		}
		return false
	})

	// Scan mock_querier_test.go for methods already implemented (non-stubs).
	implemented := findImplementedMethods()

	var buf bytes.Buffer
	fmt.Fprintln(&buf, "// Code generated by gen_mock_querier.go; DO NOT EDIT.")
	fmt.Fprintln(&buf, "// Regenerate with: go generate ./internal/pipeline/")
	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "package pipeline")
	fmt.Fprintln(&buf)
	// pgtype appears in querier signatures (e.g. pgtype.UUID params) whenever
	// a query uses one directly; import it only when a stub references it so
	// gofmt/vet stay clean either way.
	needsPgtype := false
	for _, m := range methods {
		if implemented[m.name] {
			continue
		}
		if strings.Contains(m.params, "pgtype.") || strings.Contains(m.returns, "pgtype.") {
			needsPgtype = true
			break
		}
	}
	fmt.Fprintln(&buf, "import (")
	fmt.Fprintln(&buf, "\t\"context\"")
	fmt.Fprintln(&buf)
	if needsPgtype {
		fmt.Fprintln(&buf, "\t\"github.com/jackc/pgx/v5/pgtype\"")
		fmt.Fprintln(&buf)
	}
	fmt.Fprintln(&buf, "\tdb \"openloc/internal/database/sqlcgen\"")
	fmt.Fprintln(&buf, ")")
	fmt.Fprintln(&buf)

	var stubCount int
	for _, m := range methods {
		if implemented[m.name] {
			continue // already implemented in mock_querier_test.go
		}
		stubCount++
		fmt.Fprintf(&buf, "func (m *mockQuerier) %s(%s) %s { panic(\"not used\") }\n",
			m.name, m.params, m.returns)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// If formatting fails, write unformatted so the user sees the error
		os.Stdout.Write(buf.Bytes())
		log.Fatalf("gofmt: %v", err)
	}

	outPath := "mock_querier_stubs_test.go"
	if err := os.WriteFile(outPath, formatted, 0644); err != nil {
		log.Fatalf("write %s: %v", outPath, err)
	}
	fmt.Printf("wrote %s (%d stubs, %d implemented)\n", outPath, stubCount, len(implemented))
}

type method struct {
	name    string
	params  string
	returns string
}

func parseMethod(name string, ft *ast.FuncType, fset *token.FileSet) method {
	params := renderFieldList(ft.Params, fset)
	returns := renderResults(ft.Results, fset)
	return method{name: name, params: params, returns: returns}
}

func renderFieldList(fl *ast.FieldList, fset *token.FileSet) string {
	if fl == nil || len(fl.List) == 0 {
		return ""
	}
	var parts []string
	for _, f := range fl.List {
		typ := qualifyType(f.Type, fset)
		if len(f.Names) == 0 {
			parts = append(parts, typ)
		} else {
			for range f.Names {
				parts = append(parts, typ)
			}
		}
	}
	return strings.Join(parts, ", ")
}

func renderResults(fl *ast.FieldList, fset *token.FileSet) string {
	if fl == nil || len(fl.List) == 0 {
		return ""
	}
	var parts []string
	for _, f := range fl.List {
		typ := qualifyType(f.Type, fset)
		if len(f.Names) == 0 {
			parts = append(parts, typ)
		} else {
			for range f.Names {
				parts = append(parts, typ)
			}
		}
	}
	if len(parts) == 1 {
		return parts[0]
	}
	return "(" + strings.Join(parts, ", ") + ")"
}

// builtinTypes that don't need a db. prefix
var builtinTypes = map[string]bool{
	"bool": true, "byte": true, "complex64": true, "complex128": true,
	"error": true, "float32": true, "float64": true,
	"int": true, "int8": true, "int16": true, "int32": true, "int64": true,
	"rune": true, "string": true,
	"uint": true, "uint8": true, "uint16": true, "uint32": true, "uint64": true, "uintptr": true,
	"context.Context": true,
}

func qualifyType(n ast.Node, fset *token.FileSet) string {
	switch t := n.(type) {
	case *ast.Ident:
		name := t.Name
		if builtinTypes[name] {
			return name
		}
		return "db." + name
	case *ast.SelectorExpr:
		// Already qualified (e.g., context.Context)
		return nodeString(n, fset)
	case *ast.ArrayType:
		return "[]" + qualifyType(t.Elt, fset)
	case *ast.StarExpr:
		return "*" + qualifyType(t.X, fset)
	default:
		return nodeString(n, fset)
	}
}

// findImplementedMethods scans mock_querier_test.go for methods that have
// real implementations (not just panic stubs). These are skipped in generation.
func findImplementedMethods() map[string]bool {
	candidates := []string{
		"mock_querier_test.go",
		"internal/pipeline/mock_querier_test.go",
	}
	var path string
	for _, c := range candidates {
		if _, err := os.Stat(c); err == nil {
			path = c
			break
		}
	}
	if path == "" {
		return nil
	}

	f, err := os.Open(path)
	if err != nil {
		return nil
	}
	defer f.Close()

	methodRe := regexp.MustCompile(`^func \(m \*mockQuerier\) (\w+)\(`)
	implemented := make(map[string]bool)

	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := scanner.Text()
		m := methodRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		name := m[1]
		// Skip if this is a panic-only stub (single-line)
		if strings.Contains(line, `panic("not used")`) && strings.HasSuffix(strings.TrimSpace(line), "}") {
			continue
		}
		implemented[name] = true
	}
	return implemented
}

func nodeString(n ast.Node, fset *token.FileSet) string {
	var buf bytes.Buffer
	if err := format.Node(&buf, fset, n); err != nil {
		return fmt.Sprintf("/* ERROR: %v */", err)
	}
	return buf.String()
}
