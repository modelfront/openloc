#!/usr/bin/env bash
# Tests scripts/check-sqlc.sh against a fake `sqlc` on PATH, so the check is
# proven able to fail without sqlc installed: a gate that cannot fail is no gate.
#
#   bash scripts/check-sqlc.test.sh
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
check="$root/scripts/check-sqlc.sh"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
failures=0

# A repo with only the generated header, and a fake sqlc that prints
# $FAKE_SQLC_VERSION and exits $FAKE_SQLC_DIFF from `sqlc diff`.
mkdir -p "$T/repo/internal/database/sqlcgen" "$T/bin"
printf '// Code generated by sqlc. DO NOT EDIT.\n// versions:\n//   sqlc v1.30.0\n\npackage db\n' \
  > "$T/repo/internal/database/sqlcgen/db.go"
cat > "$T/bin/sqlc" <<'EOF'
#!/bin/sh
case "$1" in
  version) echo "$FAKE_SQLC_VERSION" ;;
  diff) [ "$FAKE_SQLC_DIFF" = 0 ] || echo "--- a/queries.sql.go"; exit "$FAKE_SQLC_DIFF" ;;
esac
EOF
chmod +x "$T/bin/sqlc"

# run <expected exit> <path> <version> <diff exit>: keeps the output in $out.
run() {
  local want="$1"
  set +e
  out="$(PATH="$2" FAKE_SQLC_VERSION="$3" FAKE_SQLC_DIFF="$4" "$check" "$T/repo" 2>&1)"
  local got=$?
  set -e
  [ "$got" = "$want" ] || { echo "  FAIL  exit $got, wanted $want:"; printf '%s\n' "$out" | sed 's/^/        /'; failures=$((failures + 1)); }
}
has() { if printf '%s\n' "$out" | grep -qF -- "$1"; then echo "  ok    $2"; else echo "  FAIL  $2 (output lacks: $1)"; failures=$((failures + 1)); fi; }

with_fake="$T/bin:/usr/bin:/bin"

echo "generated code that matches passes"
run 0 "$with_fake" v1.30.0 0
has "matches the queries (sqlc v1.30.0)" "says so"

echo "stale generated code fails"
run 1 "$with_fake" v1.30.0 1
has "is stale: run 'make sqlc'" "names the fix"

echo "another sqlc version fails before diffing"
run 1 "$with_fake" v1.31.0 0
has "sqlc here is 'v1.31.0': install v1.30.0" "names both versions"

echo "no sqlc fails"
run 1 /usr/bin:/bin v1.30.0 0
has "'not installed': install v1.30.0" "names the version to install"

echo "a header without a version fails"
printf 'package db\n' > "$T/repo/internal/database/sqlcgen/db.go"
run 1 "$with_fake" v1.30.0 0
has "no sqlc version in the header" "says what is missing"

if [ "$failures" -gt 0 ]; then
  echo "check-sqlc-test: $failures failed"
  exit 1
fi
echo "check-sqlc-test: all passed"
